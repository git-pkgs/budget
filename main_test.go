func buildCLI(t *testing.T) string {
	t.Helper()
	binary := filepath.Join(t.TempDir(), "budget")
	if runtime.GOOS == "windows" {
		binary += ".exe"
	}
	if output, err := exec.Command("go", "build", "-o", binary, ".").CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, output)
	}
	return binary
}

func TestHelpExitStatus(t *testing.T) {
	binary := buildCLI(t)
	for _, arg := range []string{"-h", "-help"} {
		cmd := exec.Command(binary, arg)
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		output, err := cmd.Output()
		if err != nil || stderr.Len() != 0 || !bytes.Contains(output, []byte("Usage of budget:")) {
			t.Fatalf("%s: err=%v stderr=%q stdout=%q", arg, err, &stderr, output)
		}
	}
	if err := exec.Command(binary, "-unknown").Run(); err == nil {
		t.Fatal("unknown flag exited successfully")
	}
}

