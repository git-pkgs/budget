func TestCLI(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"main.go": `package example
// Example command callback.
var run = func(ok bool) {
	if ok && ready() { work() }
}
func outer() {
	// A nested callback gets its own budget.
	fn := func() {
		for ready() { work() }
	}
	fn()
}
`,
		"main_test.go":       "package example\nfunc TestExample() {}\n",
		"generated.go":       "// Code generated by example. DO NOT EDIT.\npackage example\nfunc Generated() {}\n",
		"testdata/broken.go": "this is not Go",
		"vendor/broken.go":   "this is not Go",
		".hidden/broken.go":  "this is not Go",
	}
	for name, source := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(source), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	var output bytes.Buffer
	if err := run([]string{"-json", dir}, &output); err != nil {
		t.Fatal(err)
	}
	var data measurements
	if err := json.Unmarshal(output.Bytes(), &data); err != nil {
		t.Fatal(err)
	}
	got := data.Functions
	if len(got) != 3 {
		t.Fatalf("functions = %v", got)
	}
	for i, want := range []struct{ line, loc, cc int }{{3, 5, 3}, {6, 4, 1}, {8, 5, 2}} {
		if got[i].Line != want.line || got[i].LOC != want.loc || got[i].CC != want.cc {
			t.Errorf("function %d = %+v, want %+v", i, got[i], want)
		}
	}
	output.Reset()
	if err := run([]string{"-tests", "-at", "1", "-power", "0", dir}, &output); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(output.String(), "4 functions;") || !strings.Contains(output.String(), "Top violations for p=0:") || !strings.Contains(output.String(), "main.go:3") {
		t.Fatal(output.String())
	}
}

func TestBranchCounting(t *testing.T) {
	source := `package example
func branches(x int, ch chan int) {
	if x > 0 || x < -1 { }
	for i := 0; i < x; i++ { }
	for range ch { }
	switch x { case 1, 2: case 3: default: }
	select { case <-ch: default: }
	switch any(x).(type) { case int: default: }
}
`
	got, err := measure("example.go", []byte(source))
	if err != nil {
		t.Fatal(err)
	}
	if len(got.Functions) != 1 || got.Functions[0].CC != 9 {
		t.Fatalf("measurements = %+v", got)
	}
}

func TestFormattingAndComments(t *testing.T) {
	plain := "package example\nfunc f(x bool) { if x { println(1) } }\n"
	commented := "package example\n// doc\nfunc f(x bool) {\n\n/* multi\nline */ if x { // inline\nprintln(1)\n}\n}\n"
	a, err := measure("a.go", []byte(plain))
	if err != nil {
		t.Fatal(err)
	}
	b, err := measure("b.go", []byte(commented))
	if err != nil {
		t.Fatal(err)
	}
	if a.LOC != b.LOC || a.Functions[0].CC != b.Functions[0].CC {
		t.Fatalf("formatting changed metrics: %+v vs %+v", a, b)
	}
}

