func TestCLIExclusionsAndRelativePaths(t *testing.T) {
	dir := t.TempDir()
	if err := os.Mkdir(filepath.Join(dir, "testdata"), 0o755); err != nil {
		t.Fatal(err)
	}
	for name, source := range map[string]string{
		"example.go":         "package example\nfunc f() {}\n",
		"testdata/broken.go": "invalid Go",
	} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(source), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	t.Chdir(filepath.Dir(dir))
	relative := filepath.Base(dir)
	var previous measurements
	for _, root := range []string{dir, relative} {
		var out bytes.Buffer
		if err := run([]string{"-json", "-exclude", "vendor, testdata, ,", root}, &out); err != nil {
			t.Fatal(err)
		}
		var got measurements
		if err := json.Unmarshal(out.Bytes(), &got); err != nil {
			t.Fatal(err)
		}
		if len(got.Files) != 1 || got.Files[0].Name != "example.go" {
			t.Fatalf("files: %+v", got.Files)
		}
		if got.Functions[0].File != "example.go" || got.Files[0].Package != ".:example" {
			t.Fatalf("measurements: %+v", got)
		}
		if previous.Files != nil && !reflect.DeepEqual(previous, got) {
			t.Fatal("root spelling changed JSON measurements")
		}
		previous = got
	}
	var out bytes.Buffer
	if err := run([]string{"-json", filepath.Join(dir, "example.go")}, &out); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), `"File":"example.go"`) {
		t.Fatal(out.String())
	}
}

